// Customer profile page (name/phone/avatar + saved address book). Opt-in
// against a real database, same convention as
// auth.account-recovery.integration.test.ts and commerce.database.integration.test.ts.
const describeWithDatabase = process.env.RUN_AUTH_INTEGRATION_TESTS === "1" ? describe : describe.skip;

// A real 4x4 PNG generated by sharp itself and verified to survive the
// FULL processUploadedImage pipeline (rotate + resize + re-encode), not
// just assertImageSignature's magic-byte check or sharp's lightweight
// .metadata() read — both of those can pass on a fixture whose actual
// pixel/IDAT data is malformed, which then blows up libpng at the real
// decode step this route now performs. Regenerate via:
//   sharp({ create: { width: 4, height: 4, channels: 4, background: {...} } }).png().toBuffer()
const TINY_PNG_BASE64 = "iVBORw0KGgoAAAANSUhEUgAAAAQAAAAECAYAAACp8Z5+AAAACXBIWXMAAAPoAAAD6AG1e1JrAAAAEklEQVQImWM4IWf0HxkzkC4AAGuYIXGU5TmSAAAAAElFTkSuQmCC";

function makeCaller(user: TrpcContext["user"]) {
  const ctx: TrpcContext = {
    user,
    req: { protocol: "https", headers: {}, ip: `127.0.0.${Math.floor(Math.random() * 250) + 1}`, socket: { remoteAddress: "127.0.0.1" } } as unknown as TrpcContext["req"],
    res: { cookie: () => undefined, clearCookie: () => undefined } as unknown as TrpcContext["res"],
  };
  return appRouter.createCaller(ctx);
}

describeWithDatabase("customer profile integration", () => {
  const marker = `profile-test-${Date.now()}`;
  let userId = 0;
  let otherUserId = 0;
  let sessionUser: TrpcContext["user"];
  let otherSessionUser: TrpcContext["user"];

  beforeAll(async () => {
    const db = await getDb();
    if (!db) throw new Error("DATABASE_URL is required for profile integration tests.");
    const inserted = await db.insert(users).values({
      email: `${marker}@example.invalid`,
      passwordHash: await hashPassword("Passw0rd!123"),
      name: "Profile Test User",
      role: "user",
      emailVerifiedAt: new Date(),
    });
    userId = Number(inserted[0].insertId);
    sessionUser = { id: userId, email: `${marker}@example.invalid`, name: "Profile Test User", role: "user", emailVerifiedAt: new Date(), sessionVersion: 0, phone: null, avatarUrl: null, suspendedAt: null, suspendedReason: null, createdAt: new Date(), updatedAt: new Date(), lastSignedIn: new Date() };

    const insertedOther = await db.insert(users).values({
      email: `${marker}-other@example.invalid`,
      passwordHash: await hashPassword("Passw0rd!123"),
      name: "Other Test User",
      role: "user",
      emailVerifiedAt: new Date(),
    });
    otherUserId = Number(insertedOther[0].insertId);
    otherSessionUser = { ...sessionUser, id: otherUserId, email: `${marker}-other@example.invalid`, name: "Other Test User" };
  });

  afterAll(async () => {
    const db = await getDb();
    if (!db) return;
    for (const id of [userId, otherUserId]) {
      if (!id) continue;
      await db.delete(userAddresses).where(eq(userAddresses.userId, id));
      await db.delete(users).where(eq(users.id, id));
    }
  });

  it("rejects anonymous access to every profile procedure", async () => {
    const caller = makeCaller(null);
    await expect(caller.profile.update({ name: "Nope" })).rejects.toMatchObject({ code: "UNAUTHORIZED" });
    await expect(caller.profile.addresses.list()).rejects.toMatchObject({ code: "UNAUTHORIZED" });
    await expect(caller.profile.addresses.create({ label: "Гэр", recipientName: "Test", phone: "99001122", addressLine: "Test address line" })).rejects.toMatchObject({ code: "UNAUTHORIZED" });
  });

  it("updates name and phone, leaving email/role untouched", async () => {
    const caller = makeCaller(sessionUser);
    const updated = await caller.profile.update({ name: "Шинэ Нэр", phone: "99112233" });
    expect(updated.name).toBe("Шинэ Нэр");
    expect(updated.phone).toBe("99112233");
    expect(updated.email).toBe(sessionUser!.email);
    expect(updated.role).toBe("user");
    expect((updated as Record<string, unknown>).passwordHash).toBeUndefined();
  });

  it("uploads and removes an avatar", async () => {
    const caller = makeCaller(sessionUser);
    const uploaded = await caller.profile.uploadAvatar({ fileName: "me.png", contentType: "image/png", dataBase64: TINY_PNG_BASE64 });
    expect(uploaded.avatarUrl).toBeTruthy();

    const removed = await caller.profile.removeAvatar();
    expect(removed.avatarUrl).toBeNull();
  });

  it("makes the first saved address the default automatically, then lets a second default swap it", async () => {
    const caller = makeCaller(sessionUser);
    const first = await caller.profile.addresses.create({ label: "Гэр", recipientName: "Батаа", phone: "99001122", addressLine: "1-р хороо, 10-р байр" });
    expect(first.isDefault).toBe(true);

    const second = await caller.profile.addresses.create({ label: "Ажил", recipientName: "Батаа", phone: "99003344", addressLine: "Сүхбаатар дүүрэг, оффис" });
    expect(second.isDefault).toBe(false);

    const list = await caller.profile.addresses.list();
    expect(list).toHaveLength(2);
    expect(list[0].id).toBe(first.id); // default sorts first

    const promoted = await caller.profile.addresses.update({ id: second.id, isDefault: true });
    expect(promoted.isDefault).toBe(true);
    const listAfter = await caller.profile.addresses.list();
    expect(listAfter.find(item => item.id === first.id)?.isDefault).toBe(false);
    expect(listAfter.find(item => item.id === second.id)?.isDefault).toBe(true);
  });

  it("promotes the next address to default when the default one is deleted", async () => {
    const caller = makeCaller(sessionUser);
    const list = await caller.profile.addresses.list();
    const defaultAddress = list.find(item => item.isDefault)!;
    await caller.profile.addresses.delete({ id: defaultAddress.id });
    const remaining = await caller.profile.addresses.list();
    expect(remaining).toHaveLength(1);
    expect(remaining[0].isDefault).toBe(true);
  });

  it("never lets one user read, edit, or delete another user's address", async () => {
    const owner = makeCaller(sessionUser);
    const intruder = makeCaller(otherSessionUser);
    const mine = await owner.profile.addresses.list();
    const targetId = mine[0].id;

    const intruderList = await intruder.profile.addresses.list();
    expect(intruderList.find(item => item.id === targetId)).toBeUndefined();

    await expect(intruder.profile.addresses.update({ id: targetId, label: "Hijacked" })).rejects.toMatchObject({ code: "NOT_FOUND" });
    await expect(intruder.profile.addresses.delete({ id: targetId })).rejects.toMatchObject({ code: "NOT_FOUND" });
  });

  it("saves Beauty & Home preferences", async () => {
    const caller = makeCaller(sessionUser);
    const updated = await caller.profile.updatePreferences({ skinType: "combination", skinConcerns: "acne,dullness", interiorStyle: "minimal" });
    expect(updated.skinType).toBe("combination");
    expect(updated.skinConcerns).toBe("acne,dullness");
    expect(updated.interiorStyle).toBe("minimal");
  });

  it("toggles notification preferences independently", async () => {
    const caller = makeCaller(sessionUser);
    const emailOff = await caller.profile.updateNotifications({ emailOptIn: false });
    expect(emailOff.emailOptIn).toBe(false);
    expect(emailOff.smsOptIn).toBe(true); // untouched field keeps its previous value
    const smsOff = await caller.profile.updateNotifications({ smsOptIn: false });
    expect(smsOff.smsOptIn).toBe(false);
    expect(smsOff.emailOptIn).toBe(false); // stays off from the previous call
  });
});

describeWithDatabase("customer profile — change password & delete account", () => {
  const marker = `profile-security-test-${Date.now()}`;
  let userId = 0;
  let sessionUser: TrpcContext["user"];

  beforeAll(async () => {
    const db = await getDb();
    if (!db) throw new Error("DATABASE_URL is required for profile integration tests.");
    const inserted = await db.insert(users).values({
      email: `${marker}@example.invalid`,
      passwordHash: await hashPassword("OriginalPassw0rd!"),
      name: "Security Test User",
      role: "user",
      emailVerifiedAt: new Date(),
    });
    userId = Number(inserted[0].insertId);
    sessionUser = { id: userId, email: `${marker}@example.invalid`, name: "Security Test User", role: "user", emailVerifiedAt: new Date(), sessionVersion: 0, phone: null, avatarUrl: null, suspendedAt: null, suspendedReason: null, createdAt: new Date(), updatedAt: new Date(), lastSignedIn: new Date() };
  });

  afterAll(async () => {
    const db = await getDb();
    if (!db) return;
    await db.delete(users).where(eq(users.id, userId));
  });

  it("rejects the wrong current password, then changes it and re-signs a fresh cookie so the current device stays signed in", async () => {
    let cookieSet: string | undefined;
    const ctx: TrpcContext = {
      user: sessionUser,
      req: { protocol: "https", headers: {}, ip: "127.0.0.1", socket: { remoteAddress: "127.0.0.1" } } as unknown as TrpcContext["req"],
      res: { cookie: (_name: string, value: string) => { cookieSet = value; }, clearCookie: () => undefined } as unknown as TrpcContext["res"],
    };
    const caller = appRouter.createCaller(ctx);

    await expect(caller.profile.changePassword({ currentPassword: "WrongPassword!", newPassword: "BrandNewPassw0rd!" })).rejects.toMatchObject({ code: "UNAUTHORIZED" });
    await caller.profile.changePassword({ currentPassword: "OriginalPassw0rd!", newPassword: "BrandNewPassw0rd!" });
    expect(cookieSet).toBeTruthy(); // a fresh session token was issued in the same response

    const loginCaller = makeCaller(null);
    await expect(loginCaller.auth.login({ email: sessionUser!.email, password: "OriginalPassw0rd!" })).rejects.toMatchObject({ code: "UNAUTHORIZED" });
    const loggedIn = await loginCaller.auth.login({ email: sessionUser!.email, password: "BrandNewPassw0rd!" });
    expect(loggedIn.id).toBe(userId);
  });

  it("refuses to delete an admin/staff account, requires the correct password, then permanently deletes a plain user account", async () => {
    const staffCaller = makeCaller({ ...sessionUser!, role: "staff" });
    await expect(staffCaller.profile.deleteAccount({ password: "anything" })).rejects.toMatchObject({ code: "BAD_REQUEST" });

    const caller = makeCaller(sessionUser);
    await expect(caller.profile.deleteAccount({ password: "WrongPassword!" })).rejects.toMatchObject({ code: "UNAUTHORIZED" });

    await caller.profile.deleteAccount({ password: "BrandNewPassw0rd!" });
    const gone = await getUserByEmail(sessionUser!.email);
    expect(gone).toBeUndefined();
  });
});

describeWithDatabase("customer wishlist + back-in-stock alerts", () => {
  const marker = `wishlist-test-${Date.now()}`;
  let userId = 0;
  let sessionUser: TrpcContext["user"];
  let categoryId = 0;
  let productId = 0;
  let adminUserId = 0;
  let adminSessionUser: TrpcContext["user"];

  beforeAll(async () => {
    const db = await getDb();
    if (!db) throw new Error("DATABASE_URL is required for profile integration tests.");
    const inserted = await db.insert(users).values({
      email: `${marker}@example.invalid`,
      passwordHash: await hashPassword("Passw0rd!123"),
      name: "Wishlist Test User",
      role: "user",
      emailVerifiedAt: new Date(),
    });
    userId = Number(inserted[0].insertId);
    sessionUser = { id: userId, email: `${marker}@example.invalid`, name: "Wishlist Test User", role: "user", emailVerifiedAt: new Date(), sessionVersion: 0, phone: null, avatarUrl: null, suspendedAt: null, suspendedReason: null, createdAt: new Date(), updatedAt: new Date(), lastSignedIn: new Date() };

    // admin.updateProduct writes an admin_audit_logs row whose actorUserId is
    // a RESTRICT foreign key to users.id, so the acting "admin" here has to
    // be a real row too, not just an in-memory ctx.user object.
    const insertedAdmin = await db.insert(users).values({
      email: `${marker}-admin@example.invalid`,
      passwordHash: await hashPassword("Passw0rd!123"),
      name: "Wishlist Test Admin",
      role: "admin",
      emailVerifiedAt: new Date(),
    });
    adminUserId = Number(insertedAdmin[0].insertId);
    adminSessionUser = { ...sessionUser, id: adminUserId, role: "admin", email: `${marker}-admin@example.invalid` };

    const categoryResult = await db.insert(productCategories).values({ name: "Wishlist test category", slug: `${marker}-category`, sortOrder: 99999, isActive: true });
    categoryId = Number(categoryResult[0].insertId);
    const productResult = await db.insert(products).values({ categoryId, name: "Wishlist test product", slug: `${marker}-product`, sku: `${marker}-SKU`, priceMnt: 12_000, stockQuantity: 0, isPublished: true });
    productId = Number(productResult[0].insertId);
  });

  afterAll(async () => {
    const db = await getDb();
    if (!db) return;
    await db.delete(wishlistItems).where(eq(wishlistItems.productId, productId));
    await db.delete(products).where(eq(products.id, productId));
    await db.delete(productCategories).where(eq(productCategories.id, categoryId));
    await db.delete(users).where(eq(users.id, userId));
    await db.delete(adminAuditLogs).where(eq(adminAuditLogs.actorUserId, adminUserId));
    await db.delete(users).where(eq(users.id, adminUserId));
  });

  it("adds, lists, and removes a wishlist item, including the not-yet-in-stock notify flag", async () => {
    const caller = makeCaller(sessionUser);
    await caller.profile.wishlist.toggle({ productId, saved: true, notifyOnRestock: true });

    const list = await caller.profile.wishlist.list();
    expect(list).toHaveLength(1);
    expect(list[0]).toMatchObject({ productId, name: "Wishlist test product", stockQuantity: 0, notifyOnRestock: true });

    await caller.profile.wishlist.toggle({ productId, saved: false });
    expect(await caller.profile.wishlist.list()).toHaveLength(0);
  });

  it("clears the notify flag once admin.updateProduct restocks 0 -> >0 (the back-in-stock alert firing)", async () => {
    const caller = makeCaller(sessionUser);
    await caller.profile.wishlist.toggle({ productId, saved: true, notifyOnRestock: true });

    await makeCaller(adminSessionUser).admin.updateProduct({ id: productId, stockQuantity: 5 });

    const list = await caller.profile.wishlist.list();
    expect(list[0].stockQuantity).toBe(5);
    expect(list[0].notifyOnRestock).toBe(false); // cleared after the (logged, Brevo-unconfigured) notification fired
  });
});
